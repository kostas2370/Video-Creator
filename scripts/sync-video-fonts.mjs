import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const fontDirectory = join(root, "backend/assets/fonts");
const manifest = JSON.parse(readFileSync(join(fontDirectory, "manifest.json"), "utf8"));
const check = process.argv.includes("--check");
const outdated = [];

function sync(relativePath, expected) {
  const target = join(root, relativePath);
  const bytes = Buffer.isBuffer(expected) ? expected : Buffer.from(expected);
  if (existsSync(target) && readFileSync(target).equals(bytes)) return;
  if (check) { outdated.push(relativePath); return; }
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, bytes);
}

const css = ["/* Generated by scripts/sync-video-fonts.mjs. Edit the backend font manifest. */"];
for (const font of manifest) {
  for (const face of font.faces) {
    const target = `frontend/public/fonts/${face.file}`;
    if (font.bundled) sync(target, readFileSync(join(fontDirectory, face.file)));
    else if (!existsSync(join(root, target))) throw new Error(`Missing system-font preview asset: ${target}`);
    css.push(`@font-face { font-family: "${font.family}"; src: url("/fonts/${face.file}") format("truetype"); font-style: normal; font-weight: ${face.weight}; font-display: swap; }`);
  }
  const licenseTarget = `frontend/public/fonts/${font.license}`;
  if (font.bundled) sync(licenseTarget, readFileSync(join(fontDirectory, font.license)));
  else if (!existsSync(join(root, licenseTarget))) throw new Error(`Missing font license: ${licenseTarget}`);
}
sync("frontend/src/generated/videoFonts.json", JSON.stringify(manifest, null, 2) + "\n");
sync("frontend/src/videoFonts.css", css.join("\n") + "\n");
if (outdated.length) {
  throw new Error(`Font artifacts are out of date: ${outdated.join(", ")}. Run npm run fonts:sync from frontend.`);
}
